def human_audit() -> None:
    import yaml
    rows = []
    ttj = {r["key"]: r["response_en"] for r in read_jsonl(LABELS / "ttj.jsonl")}
    for m in ("gemma_it", "gams3_it"):
        p = WORK / f"dose_addendum_{m}.yaml"
        if not p.exists():
            continue
        tag = yaml.safe_load(p.read_text())["dose_star_tag"]
        G = [r for r in read_jsonl(GENS / f"{m}.jsonl") if r["kind"] == "harmful" and r["dose_tag"] == tag
             and r["arm"] != "EN_orig"]
        for out_lang, cell in (("en", "EN>EN"), ("sl", "EN>SL")):
            sub = sorted([r for r in G if r["cell"] == cell], key=lambda r: sha1_int("iter5_human|" + r["key"]))[:60]
            rows += [{"key": r["key"], "model_hidden": True, "cell_hidden": True, "response": r["response"],
                      "nllb_english": ttj.get(r["key"], "") if out_lang == "sl" else "",
                      "human_refused": None, "human_class4": None, "human_harmful_actionable": None,
                      "annotator_native_slovene": None} for r in sub]
    dump(RESULTS / "human_audit_request.json", {
        "status": "REQUESTED, NOT PERFORMED", "who": "a native Slovene speaker (plus one English annotator)",
        "why": "all reference labels in this artifact are LLM adjudication; a shared Slovene bias across LLM families "
               "cannot be removed by the correction", "spec": "60 hash-sampled edited rows per model x reply language "
               "(EN, SL) at dose*; blind to model / cell; fields as in exp14's request", "n": len(rows), "rows": rows})


def freeze_order() -> None:
    def gitlog(path: str) -> str:
        r = subprocess.run(["git", "log", "--format=%cI", "--diff-filter=A", "--", path], cwd=ROOT,
                           capture_output=True, text=True)
        return (r.stdout.strip().splitlines() or [""])[-1]
    fz = gitlog("protocol.yaml")
    first_rows = {}
    for m in MODELS:
        rs = read_jsonl(GENS / f"{m}.jsonl")
        if rs:
            first_rows[m] = min(r["t"] for r in rs)
    dev = {}
    for m in MODELS:
        rs = read_jsonl(GENS / f"dev_{m}.jsonl")
        if rs:
            dev[m] = min(r["t"] for r in rs)
    led = read_jsonl(LEDGER / "ledger.jsonl")
    first_paid = datetime.utcfromtimestamp(min(x["ts"] for x in led)).isoformat() + "+00:00" if led else None
    add = {m: gitlog(f"dose_addendum_{m}.yaml") for m in ("gemma_it", "gams3_it")}

    def ts(x):
        return datetime.fromisoformat(x).timestamp() if x else None
    ok = all(ts(fz) < ts(v) for v in list(first_rows.values()) + list(dev.values()) if v) and \
        (first_paid is None or ts(fz) < ts(first_paid)) and \
        all(ts(add[m]) < ts(first_rows[m]) for m in add if add[m] and m in first_rows)
    dump(RESULTS / "freeze_order_check.json", {"protocol_commit": fz, "first_dev_row": dev, "first_conf_row": first_rows,
                                               "first_paid_call": first_paid, "dose_addendum_commit": add,
                                               "protocol_sha256_matches": sha256_file(ROOT / "protocol.yaml") ==
                                               (ROOT / "protocol.sha256").read_text().split()[0], "order_ok": ok})


def main() -> None:
    method_out()
    tables()
    human_audit()
    freeze_order()
    if WORK == ROOT:
        readme_results()
    _ = DATA


if __name__ == "__main__":
    main()
