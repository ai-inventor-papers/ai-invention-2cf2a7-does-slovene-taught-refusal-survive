#!/usr/bin/env python3
"""S12 OUTPUTS: method_out.json (exp_gen_sol_out; one example per generated CONF/twin row; predict_* = labels, all
strings), results/RESULTS_tables.md (generated from analysis.json; NO hand-typed numbers), results/
human_audit_request.json (REQUESTED, NOT PERFORMED), results/freeze_order_check.json."""
from __future__ import annotations

import json
import subprocess
from datetime import datetime

from common import WORK, ADJ, DATA, GENS, LABELS, LEDGER, RESULTS, ROOT, dump, read_jsonl, sha1_int, sha256_file

MODELS = ("gemma_it", "gams3_it", "pew_heretic", "huihui", "mlabonne_v2")


def s(x) -> str:
    return "" if x is None else str(x)


def method_out() -> None:
    gem = {r["key"]: r for r in read_jsonl(LABELS / "gemini.jsonl") if r["readout"] == "gemini"}
    loc: dict = {}
    for r in read_jsonl(LABELS / "local.jsonl"):
        loc.setdefault(r["key"], {})[r["readout"]] = r
    ttj = {r["key"]: r["response_en"] for r in read_jsonl(LABELS / "ttj.jsonl")}
    adj = {r["key"]: r for r in read_jsonl(ADJ / "resolved.jsonl")}
    ds = []
    for m in MODELS:
        rows = read_jsonl(GENS / f"{m}.jsonl")
        if not rows:
            continue
        ex = []
        for r in rows:
            g, lo, a = gem.get(r["key"], {}), loc.get(r["key"], {}), adj.get(r["key"], {})
            e = {"input": r["user_turn"], "output": r["response"],
                 "predict_gemini_U": s(g.get("U")), "predict_gemini_score": s(g.get("score")),
                 "predict_gemini_refused": s(g.get("refused")), "predict_gemini_blocked": s(g.get("blocked")),
                 "predict_local_sr_U": s((lo.get("sr_local") or {}).get("U")),
                 "predict_local_sr_score": s((lo.get("sr_local") or {}).get("score")),
                 "predict_j1": s((lo.get("j1") or {}).get("label")),
                 "predict_ttj_j1": s((lo.get("ttj_j1") or {}).get("label")),
                 "predict_adj_U": s(a.get("adj_U")), "predict_adj_class4": s(a.get("adj_class4"))}
            for k in ("key", "model", "revision", "dose_tag", "lambda", "cell", "in_lang", "out_lang", "suffix",
                      "backup_suffix", "arm", "item_id", "kind", "source", "category", "n_new_tokens", "finish_reason",
                      "degenerate", "lid", "lid_ok", "template_sha1", "adapter_sha256", "t", "max_new"):
                e[f"metadata_{k}"] = r.get(k)
            e["metadata_response_en_nllb"] = ttj.get(r["key"])
            ex.append(e)
        ds.append({"dataset": f"iter5_conf_{m}", "examples": ex})
    A = json.loads((RESULTS / "analysis.json").read_text())
    out = {"metadata": {"method_name": "Held-out confirmation of C-OUT (reply-language safety reserve)",
                        "description": "Gemma-3-12B-IT vs GaMS3-12B-Instruct under the exp9 English Heretic edit "
                                       "(lambda-scaled LoRA hooks), 294 never-generated CONF items + 100 benign twins",
                        "baselines": ["unedited model (lambda 0)", "English->English cell (reference language)",
                                      "norm-matched random-direction edit", "sibling model GaMS3",
                                      "public abliterated checkpoint p-e-w/heretic (C-EXT)", "EN_orig MT-noise control"],
                        "verdict": A.get("verdicts", {}).get("D6_final"),
                        "primary_estimator": A.get("rg_identifiability", {}).get("primary_estimator"),
                        "protocol_sha256": sha256_file(ROOT / "protocol.yaml")},
           "datasets": ds}
    (WORK / "method_out.json").write_text(json.dumps(out, ensure_ascii=False))


def fmt(e, k="est") -> str:
    if not e or e.get(k) is None:
        return "n/a"
    ci = e.get("ci95") or [None, None]
    if ci[0] is None:
        return f"{e[k]:+.2f}"
    return f"{e[k]:+.2f} [{ci[0]:+.2f}, {ci[1]:+.2f}]"


