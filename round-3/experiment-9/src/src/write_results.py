#!/usr/bin/env python3
"""results/summary_tables.md: every number rendered programmatically from results/analysis.json + results/audit.json
(no hand-typed numbers). RESULTS.md / README.md quote these tables."""
from __future__ import annotations

import json

from common import RESULTS

NAME = {"gemma_it": "Gemma-3-12B-IT", "gams3_it": "GaMS3-12B-Instruct"}


def f(x, d=2):
    if x is None:
        return "–"
    if isinstance(x, (list, tuple)):
        return "[" + ", ".join(f(v, d) for v in x) + "]"
    if isinstance(x, float):
        return f"{x:.{d}f}"
    return str(x)


def main():
    A = json.loads((RESULTS / "analysis.json").read_text())
    au = json.loads((RESULTS / "audit.json").read_text()) if (RESULTS / "audit.json").exists() else {}
    L = ["# Summary tables (auto-generated by src/write_results.py from results/analysis.json)", ""]
    L += [f"Rows: {A['n_rows']} generations; J1-labelled {A['n_rows_j1']}; J2-labelled {A['n_rows_j2']}.",
          f"Steps used: {len(A['steps_used']['trials'])} paired trials, {len(A['steps_used']['lambda'])} lambda steps; "
          f"excluded (QC) trials {A['steps_used']['trials_excluded']}, lambda {A['steps_used']['lambda_excluded']}.", ""]
    v = A["verdict"]
    L += ["## Pre-registered verdict", "", f"**{v['verdict']}**", "", "| condition | met |", "|---|---|"]
    L += [f"| {k} | {v2} |" for k, v2 in v["conditions"].items()]
    L += [f"| REFUTE condition (90% CI inside +/-m and MDE <= 2m) | {v['refute_condition']} |", ""]
    L += ["## G3 = a_GaMS - a_Gemma (SL-MT refusal log-odds at EN-BT refusal 50%)", "",
          "| analysis | G3 | 90% CI | 95% CI | MDE | isotonic G3 | support ok | verdict (m=0.675) | verdict (m=0.20) |",
          "|---|---|---|---|---|---|---|---|---|"]
    for k, g in A["G3"].items():
        L.append(f"| {k} | {f(g['G3'])} | {f(g['ci90'])} | {f(g['ci95'])} | {f(g['mde'])} | {f(g.get('G3_isotonic'))} | "
                 f"{g['support_ok']} | {g['verdict_m']} | {g['verdict_m_local']} |")
    L += ["", "### Per-model fits", "", "| analysis | model | a | b | SL-EN gap (pp) at EN 50% | EN range | support (#[.2,.5), #[.5,.8]) |",
          "|---|---|---|---|---|---|---|"]
    for k in ("Bprime|j1|R1", "lambda|j1|R1", "Bprime|j1|R2", "Bprime|j2|R1|G_rows", "Bprime|j1|R1|G_rows"):
        if k not in A["G3"]:
            continue
        for m, pm in A["G3"][k]["per_model"].items():
            L.append(f"| {k} | {NAME[m]} | {f(pm['a'])} | {f(pm['b'])} | {f(pm['gap_pp_at_EN50'], 1)} | {f(pm['en_range'])} | "
                     f"{pm['support']} |")
    L += ["", "### Per-step rates (J1 R1, Hautus): EN-BT / SL-MT", ""]
    for k in ("lambda|j1|R1", "Bprime|j1|R1"):
        for m, pm in A["G3"][k]["per_model"].items():
            L.append(f"- {k} {NAME[m]}: EN " + " ".join(f(x) for x in pm["pE"]) + " | SL " + " ".join(f(x) for x in pm["pS"]))
    L += ["", "### Placebos", ""]
    for k, p in A["placebos"].items():
        L.append(f"- {k}: observed {f(p['observed'])}, null mean {f(p['null_mean'])} (sd {f(p['null_sd'])}), p = {f(p['p_two_sided'], 4)}, centred {p['centred']}")
    L += ["", "## Signal detection (J1 R1; window = steps with EN-BT harmful refusal in [0.3, 0.7])", "",
          "| readout | model | n window | Delta-c (SL-EN) | 95% CI | Delta-d' | 95% CI | FA excess SL-EN (p_EN<=.5) | reading |",
          "|---|---|---|---|---|---|---|---|---|"]
    for rk in ("j1|R1", "j1|R2"):
        for m, r in A["SDT"][rk]["per_model"].items():
            L.append(f"| {rk} | {NAME[m]} | {r['n_window']} | {f(r.get('delta_c'))} | {f(r.get('delta_c_ci95'))} | "
                     f"{f(r.get('delta_dprime'))} | {f(r.get('delta_dprime_ci95'))} | {f(r.get('fa_sl_minus_en_at_pEN_le_0.5'))} "
                     f"{f(r.get('fa_excess_ci95'))} | {r.get('reading')} |")
        s = A["SDT"][rk]
        if "did_c" in s:
            L.append(f"| {rk} | DiD Gemma-GaMS | | {f(s['did_c'])} | {f(s['did_c_ci95'])} | {f(s['did_dprime'])} | {f(s['did_dprime_ci95'])} | | |")
    L += ["", f"FA floor flag (all benign FA < 5% at orig): {A['SDT'].get('fa_floor_flag')}", ""]
    L += ["## Original-model rates (J1 R1, raw)", "", "| model | cell | rate | n |", "|---|---|---|---|"]
    for m, d in A["orig_rates_j1_R1"].items():
        for c, r in d.items():
            L.append(f"| {NAME[m]} | {c} | {f(r['rate_raw'], 3)} | {r['n']} |")
    L += ["", "## MT-noise check (J1 R1 harmful): EN-orig vs EN-BT vs SL-MT", ""]
    for k, d in A["mt_noise_check"].items():
        L.append(f"- {k}: " + ", ".join(f"{a} {f(x, 3)}" for a, x in d.items()))
    L += ["", "## Random-direction control (core block C, J1 R1)", "", "| model | step | EN-BT | rel. change | SL-MT | rel. change |",
          "|---|---|---|---|---|---|"]
    for m, s in A["random_specificity"].items():
        L.append(f"| {NAME[m]} | orig | {f(s['orig_on_C']['en_bt'])} | | {f(s['orig_on_C']['sl_mt'])} | |")
        for d in s["edits"]:
            L.append(f"| {NAME[m]} | {d['step']} | {f(d['en_bt'])} | {f(d['en_bt_rel_change'])} | {f(d['sl_mt'])} | {f(d['sl_mt_rel_change'])} |")
    L += ["", "## C5a (first-token KL leakage; excess ratio = (SL/EN)_edit / (SL/EN)_random)", "",
          "| model | excess ratio | 95% CI | KL edit EN | KL edit SL | KL random EN | KL random SL |", "|---|---|---|---|---|---|---|"]
    for m, c in A["C5a"].items():
        L.append(f"| {NAME[m]} | {f(c['excess_ratio'])} | {f(c['ci95'])} | {f(c['kl_sel_en'], 4)} | {f(c['kl_sel_sl'], 4)} | "
                 f"{f(c['kl_rand_en'], 4)} | {f(c['kl_rand_sl'], 4)} |")
    J = A["judge"]
    L += ["", "## Judge validity", "", "### J1 (gemini-distilled) vs held-out archived gemini gold", "",
          "| cell | n | kappa R | kappa 3-way | gold R rate | J1 R rate |", "|---|---|---|---|---|---|"]
    for k, c in (J.get("j1_vs_heldout_gemini") or {}).items():
        L.append(f"| {k} | {c['n']} | {f(c['kappaR'])} | {f(c['kappa3'])} | {f(c['rate_R_gold'])} | {f(c['rate_R_pred'])} |")
    L += ["", "### J1 vs J2 (second family) per cell (gate: kappa R >= 0.6)", "", "| cell | n | kappa R | kappa 3 | R rate J1 | R rate J2 | pass |",
          "|---|---|---|---|---|---|---|"]
    for k, c in J.get("j1_vs_j2_cells", {}).items():
        L.append(f"| {k} | {c['n']} | {f(c['kappaR'])} | {f(c['kappa3'])} | {f(c['rateR_j1'])} | {f(c['rateR_j2'])} | {c['pass_0.6']} |")
    if "adjudication" in J:
        L += ["", "### Blind adjudication (executing agent, NOT human)", "", "| cell | n | J1 kappa R | J1 sens | J1 spec | J2 kappa R | adj R rate |",
              "|---|---|---|---|---|---|---|"]
        for k, c in J["adjudication"].items():
            L.append(f"| {k} | {c['n']} | {f(c.get('j1_kappaR'))} | {f(c.get('j1_sens_R'))} | {f(c.get('j1_spec_R'))} | "
                     f"{f(c.get('j2_kappaR'))} | {f(c.get('adj_rate_R'))} |")

    if "rogan_gladen_G3_lambda_point" in J:
        L += ["", "### Misclassification-corrected G3 (Rogan-Gladen, held-out gemini error matrices)", "",
              f"G3 (lambda curve, corrected point estimate): {f(J['rogan_gladen_G3_lambda_point'])}", "",
              "| model | lang | sensitivity(REFUSE) | specificity | n validation |", "|---|---|---|---|---|"]
        for m, c in J["rogan_gladen_per_model"].items():
            for lang, e in c["error_matrix"].items():
                L.append(f"| {NAME[m]} | {lang} | {f(e['sens_R'], 3)} | {f(e['spec_R'], 3)} | {e['n_val']} |")
    L += ["", "## Sanity", ""]
    for m, s in A["sanity"].items():
        L.append(f"- {NAME[m]}: selection {json.dumps(s.get('selection'), default=str)[:300]}; lambda1 repro "
                 f"{json.dumps(s.get('lambda1_reproduction'))}; replay {json.dumps(s.get('replay_trial1'))}; EN-BT refusal orig "
                 f"{f(s.get('en_bt_refusal_orig'))} -> lambda1 {f(s.get('en_bt_refusal_lambda1'))} (cut >= 50% rel: "
                 f"{s.get('en_cut_ge_50pct_relative')}); engine gate PASS: {(s.get('engine_gate') or {}).get('PASS')}")
    L.append(f"- pairing: {A.get('pairing_check')}")
    L.append(f"- step QC summary: {A['step_qc_summary']}; flagged: {list(A['step_qc_flagged_excluded'])}")
    if au:
        L += ["", f"## Audit (second code path): all_pass = {au.get('all_pass')} over {au.get('n_checks')} checks",
              f"failed: {[k for k, v in au['checks'].items() if not v['pass']]}"]
    (RESULTS / "summary_tables.md").write_text("\n".join(L) + "\n")
    print("summary_tables.md written")


if __name__ == "__main__":
    main()
