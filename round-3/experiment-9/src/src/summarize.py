#!/usr/bin/env python3
"""Render the headline tables of results/analysis.json + sanity.json + audit.json into results/summary_tables.md.

Every number in RESULTS.md is copied from this file (which is regenerated by method.py), so the report traces to code.
"""
from __future__ import annotations

import json
import math

from common import MODEL_ORDER, RESULTS, read_jsonl

NAME = {"gemma_it": "Gemma-3-12B-IT", "gams3_it": "GaMS3-12B-Instruct"}


def f(x, d=2):
    if x is None:
        return "–"
    if isinstance(x, (list, tuple)):
        return "[" + ", ".join(f(v, d) for v in x) + "]"
    if isinstance(x, float) and math.isnan(x):
        return "nan"
    return f"{x:.{d}f}" if isinstance(x, (int, float)) else str(x)


def main():
    A = json.loads((RESULTS / "analysis.json").read_text())
    S = json.loads((RESULTS / "sanity.json").read_text())
    AU = json.loads((RESULTS / "audit.json").read_text()) if (RESULTS / "audit.json").exists() else {}
    rows = read_jsonl(RESULTS / "items_final.jsonl")
    ro = A["primary_readout"]
    L = [f"# Summary tables (auto-generated by src/summarize.py)\n",
         f"Primary readout: **{ro}** ({A['readout_status']}); rows {A['n_rows']}, judged {A['n_judged_primary']}.\n"]
    # --- G3 table
    L.append("## G3 (GaMS − Gemma predicted SL-MT refusal log-odds at EN-BT refusal = 50%)\n")
    L.append("| curve | readout | G3 | 90% CI | 95% CI | BCa 95% | MDE | on support | x* (p_EN) | verdict m=0.675 | verdict m=0.20 |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for c in ("B", "B_plus_F5", "A1", "A2"):
        g = A["G3"].get(c, {})
        if not isinstance(g, dict):
            continue
        for rk in ("primary", "primary_unexcluded", "partial_as_refusal", "lexicon", "EXPLORATORY_emulator",
                   "EXPLORATORY_emulator_partial"):
            v = g.get(rk)
            if isinstance(v, dict) and "G3" in v:
                L.append(f"| {c} | {rk} | {f(v['G3'])} | {f(v['CI90'])} | {f(v['CI95'])} | {f(v.get('CI95_BCa'))} | "
                         f"{f(v['MDE'])} | {v['on_support']} | {f(v['x_star_pEN'])} | {v.get('verdict_m_C3')} | "
                         f"{v.get('verdict_m_local')} |")
        for rk in ("excl_mt_fragile", "incl_orig_point"):
            v = g.get(rk)
            if isinstance(v, dict) and "G3" in v:
                L.append(f"| {c} | {rk} | {f(v['G3'])} | – | {f(v['CI95'])} | – | {f(v['MDE'])} | "
                         f"{v.get('on_support', '–')} | – | – | – |")
    L.append("")
    L.append("### Per-model fits (primary readout)\n")
    L.append("| curve | model | a (SL log-odds at EN 50%) | b (slope) | SL−EN gap pp at EN 50% | isotonic SL log-odds at EN 50% | n steps | EN range | support (#[.2,.5), #[.5,.8]) |")
    L.append("|---|---|---|---|---|---|---|---|---|")
    for c in ("B", "B_plus_F5", "A1", "A2"):
        g = A["G3"].get(c, {})
        if not isinstance(g, dict) or "primary" not in g:
            continue
        for m in MODEL_ORDER:
            pm = g["primary"]["per_model"][m]
            sp = g["primary"]["support"][m]
            L.append(f"| {c} | {NAME[m]} | {f(pm['a'])} | {f(pm['b'])} | {f(pm['gap_pp_at_EN50'], 1)} | "
                     f"{f(pm['isotonic_SL_logodds_at_EN50'])} | {pm['n_steps']} | {f(sp['EN_range'])} | "
                     f"({sp['n_steps_EN_0.2_0.5']}, {sp['n_steps_EN_0.5_0.8']}) |")
    L.append("")
    L.append("### Per-step rates (primary readout; Hautus-smoothed p_EN / p_SL)\n")
    for c in ("A1", "A2", "B", "B_plus_F5"):
        g = A["G3"].get(c, {})
        if not isinstance(g, dict) or "primary" not in g:
            continue
        for m in MODEL_ORDER:
            pm = g["primary"]["per_model"][m]
            L.append(f"- {c} {NAME[m]}: EN " + " ".join(f(x) for x in pm["pEN"]) + " | SL " + " ".join(f(x) for x in pm["pSL"]))
    if "permutation" in A["G3"].get("B", {}):
        p = A["G3"]["B"]["permutation"]
        L.append(f"\nB permutation (model labels swapped within paired trials): G3_obs {f(p['G3_obs'])}, null mean "
                 f"{f(p['null_mean'])} sd {f(p['null_sd'])}, p = {f(p['p_two_sided'], 4)}")
    for c in ("B", "B_plus_F5", "A1", "A2"):
        g = A["G3"].get(c, {})
        if isinstance(g, dict) and "EXPLORATORY_dose_group" in g:
            e = g["EXPLORATORY_dose_group"]
            L.append(f"- EXPLORATORY {c} dose groups: G3_low {f(e['G3_low'])} {f(e['G3_low_CI95'])} (n={e['n_low']}), "
                     f"G3_high {f(e['G3_high'])} {f(e['G3_high_CI95'])} (n={e['n_high']}), diff {f(e['diff'])}")
        if isinstance(g, dict) and "s1_diagnostic" in g and "G3_s1_diag" in g["s1_diagnostic"]:
            L.append(f"- s1 diagnostic {c}: G3_s1 {f(g['s1_diagnostic']['G3_s1_diag'])}")
    # --- within-Gemma judge curves (gemini labels exist for Gemma only)
    gj = A.get("gemma_judge_only", {})
    if gj:
        L.append("\n## Within Gemma-3-12B-IT on the gemini judge (same rows re-read by the local substitute / lexicon / emulator)\n")
        L.append("| curve | readout | a = SL log-odds at EN 50% | b | SL−EN pp at EN 50% | steps | p_EN per step | p_SL per step |")
        L.append("|---|---|---|---|---|---|---|---|")
        for c, res in gj.items():
            for ro, v in res.items():
                L.append(f"| {c} | {ro} | {f(v['a'])} | {f(v['b'])} | {f(v['SL_minus_EN_pp_at_EN50'], 1)} | {len(v['steps'])} | "
                         f"{' '.join(f(x) for x in v['pEN'])} | {' '.join(f(x) for x in v['pSL'])} |")
    ev = RESULTS / "emulator_validation.json"
    if ev.exists():
        E = json.loads(ev.read_text())
        L.append("\n## Judge emulator validation (Gemma rows, item-grouped 5-fold CV vs gemini)\n")
        for t in ("R", "RP"):
            v = E[t]
            L.append(f"- target {t}: CV kappa {f(v['cv_kappa'])} acc {f(v['cv_acc'])}; lexicon kappa {f(v['lexicon_kappa'])} acc "
                     f"{f(v['lexicon_acc'])}; per-step rate |error| emulator mean {f(v['step_rate_abs_err_emul']['mean'], 3)} "
                     f"max {f(v['step_rate_abs_err_emul']['max'], 3)} vs lexicon mean {f(v['step_rate_abs_err_lex']['mean'], 3)} "
                     f"max {f(v['step_rate_abs_err_lex']['max'], 3)}")
        L.append("\n| arm|curve | n | kappa emul | kappa lex | rate judge | rate emul | rate lex |")
        L.append("|---|---|---|---|---|---|---|")
        for k, x in E["R"]["per_arm_curve"].items():
            L.append(f"| {k} | {x['n']} | {f(x['kappa_emul'])} | {f(x['kappa_lex'])} | {f(x['rate_judge'])} | {f(x['rate_emul'])} | {f(x['rate_lex'])} |")
        L.append("\nLeave-one-curve-out (R): " + "; ".join(f"{k}: kappa {f(v['kappa'])}, rate judge {f(v['rate_judge'])} vs emul "
                                                            f"{f(v['rate_emul'])}" for k, v in E["R"]["leave_one_curve_out"].items()))
    sc = RESULTS / "spotcheck_gams.json"
    if sc.exists():
        L.append("\n## Orchestrator (Claude) blind spot check of GaMS responses\n")
        L.append("```\n" + json.dumps(json.loads(sc.read_text()).get("summary"), indent=1) + "\n```")
    # --- verdict
    V = A.get("verdict", {})
    L.append("\n## Verdict (pre-registered)\n")
    L.append("```\n" + json.dumps(V, indent=1, default=str) + "\n```")
    L.append("C3 primary curve: " + json.dumps(A.get("C3_primary_curve")))
    # --- original models
    L.append("\n## Original models (k=0) and MT noise\n")
    L.append("| model | arm | R primary judge | R gemini | R lexicon | PARTIAL-as-refusal (primary) | mean s1 | n |")
    L.append("|---|---|---|---|---|---|---|---|")
    for m in MODEL_ORDER:
        for arm in ("en_orig", "en_bt", "sl_mt"):
            sub = [r for r in rows if r["model"] == m and r["curve"] == "orig" and r["arm"] == arm]
            if not sub:
                continue
            jf = ro if ro in ("R_gemini", "R_local") else "R_gemini"
            pf = {"R_gemini": "RP_gemini", "R_local": "RP_local"}[jf]
            rj = [r[jf] for r in sub if r.get(jf) is not None]
            rp = [r[pf] for r in sub if r.get(pf) is not None]
            rg = [r["R_gemini"] for r in sub if r["R_gemini"] is not None]
            L.append(f"| {NAME[m]} | {arm} | {f(sum(rj) / len(rj)) if rj else '–'} | {f(sum(rg) / len(rg)) if rg else '–'} | "
                     f"{f(sum(r['R_lex'] for r in sub) / len(sub))} | "
                     f"{f(sum(rp) / len(rp)) if rp else '–'} | {f(sum(r['s1'] for r in sub) / len(sub))} | {len(sub)} |")
    for k, v in A.get("MT_noise_ENorig_vs_ENBT", {}).items():
        L.append(f"- MT noise {k}: EN-orig {f(v['rate_a'])} vs EN-BT {f(v['rate_b'])}; discordant {v['n01']}/{v['n10']}, McNemar p {f(v['p'], 4)}")
    for k, v in A.get("orig_language_effect_ENBT_vs_SLMT", {}).items():
        L.append(f"- Language effect (orig) {k}: EN-BT {f(v['rate_a'])} vs SL-MT {f(v['rate_b'])}; discordant {v['n01']}/{v['n10']}, p {f(v['p'], 4)}")
    # --- depth
    L.append("\n## Depth link (C)\n")
    for gname, d in A.get("depth", {}).items():
        if not isinstance(d, dict) or "cells" not in d:
            continue
        L.append(f"### grid {gname} (readout {d['readout']}, hazard rows {d.get('n_hazard_rows')})\n")
        L.append("| model|arm | refused k0 | shallow | deep | flip rate [95% CI] | underpowered |")
        L.append("|---|---|---|---|---|---|---|")
        for k, c in d["cells"].items():
            L.append(f"| {k} | {c['n_refused_k0']} | {c['n_shallow']} | {c['n_deep']} | {f(c['flip_rate'])} {f(c['flip_CI95'])} | {c['underpowered']} |")
        for m in MODEL_ORDER:
            h = d.get("hazard", {}).get(m, {})
            if not isinstance(h, dict) or "error" in h:
                L.append(f"- {m}: {h}")
                continue
            for fit in ("full", "SL_only", "SL_plus_shallow", "catFE", "continuous_ds1", "EXPLORATORY_margin_s1_0",
                        "EXPLORATORY_margin_plus_shallow"):
                fv = h.get(fit, {})
                if isinstance(fv, dict) and "error" not in fv:
                    L.append(f"- {m} {fit}: " + "; ".join(f"{k} {f(v['coef'])} {f(v['CI95'])} p={f(v['p'], 4)}"
                                                           for k, v in fv.items() if k != "Intercept"))
            att = h.get("attenuation", {})
            L.append(f"- {m} attenuation of SL log-HR by shallow: {f(att.get('attenuation'))} CI95 {f(att.get('CI95'))} "
                     f"(logHR_SL {f(att.get('logHR_SL'))} -> {f(att.get('logHR_SL_given_shallow'))})")
        pooled = d.get("hazard", {}).get("pooled", {})
        if isinstance(pooled, dict) and "error" not in pooled:
            L.append("- pooled: " + "; ".join(f"{k} {f(v['coef'])} {f(v['CI95'])}" for k, v in pooled.items() if k != "Intercept"))
        for k, v in d.get("ed50", {}).items():
            L.append(f"- ED50 {k}: shallow median {f(v['median_shallow'])} vs deep {f(v['median_deep'])} "
                     f"(n {v['n']}), one-sided MWU p {f(v['p_shallow_earlier'], 4)}")
        L.append("- predictions: " + json.dumps(d.get("predictions"), default=str))
        L.append("")
    # --- C5a / A2 specificity
    L.append("## C5a and A2 specificity\n")
    for m, v in A.get("C5a", {}).items():
        L.append(f"- C5a {NAME[m]}: " + json.dumps(v, default=float))
    for m, v in A.get("A2_specificity", {}).items():
        L.append(f"- A2 specificity {NAME[m]}: " + json.dumps(v, default=float))
    # --- sanity
    L.append("\n## Sanity / quality\n")
    jq = S.get("judge_quality") or {}

    def ktab(title, tab):
        if not tab:
            return
        L.append(f"\n{title}\n")
        L.append("| stratum | n | kappa (R) | PABAK | kappa 3-way | agree | rate A | rate B | flagged |")
        L.append("|---|---|---|---|---|---|---|---|---|")
        for k, v in tab.items():
            L.append(f"| {k} | {v['n']} | {f(v['kappa'])} | {f(v['PABAK'])} | {f(v['kappa_3way'])} | {f(v['agree'])} | "
                     f"{f(v.get('rate_a'))} | {f(v.get('rate_b'))} | {v['flagged']} |")
    if "kappa_per_stratum" in jq:
        ktab(f"Judge agreement per stratum (F7 basis: {jq.get('kappa_per_stratum_basis', 'gemini vs gpt-4.1')}; A = first rater)",
             jq["kappa_per_stratum"])
        L.append(f"\nPooled kappa: {json.dumps(jq.get('kappa_pooled'), default=float)}; routed 403s: {jq.get('n_routed_403')}")
        if jq.get("local_vs_gemini_by_lang"):
            L.append("\nLocal substitute vs gemini by language (Gemma rows): " + json.dumps(jq["local_vs_gemini_by_lang"], default=float))
        ktab("Second family (local substitute vs second local judge) per stratum, both models",
             jq.get("kappa_second_family_per_stratum"))
        if jq.get("kappa_second_family_by_model"):
            L.append("\nSecond-family agreement by model/language: " + json.dumps(jq["kappa_second_family_by_model"], default=float))
        L.append("\nLexicon vs judge: " + json.dumps(jq.get("kappa_lexicon_vs_judge"), default=float))
        L.append("\nTruncation 64 vs 128: " + json.dumps(jq.get("truncation_64_vs_128"), default=float))
    for m in MODEL_ORDER:
        d = S.get(m, {})
        L.append(f"\n### {NAME[m]}\n")
        for k in ("batch_vs_single", "A1_lam0_harmless_kl_max", "A1_lam1_heretic_scores", "A1_lam1_iter1_reference",
                  "A1_lam1_reproduces_iter1_within_0.05", "unedited_kl_noise_floor_max", "B_replay_trial1",
                  "lambda_harmless_kl", "a2_collateral", "harmless_over_refusal", "sl_lang_ok_per_step", "prefill_k_actual"):
            L.append(f"- {k}: {json.dumps(d.get(k), default=float)}")
        rd = d.get("A2_random_directions") or {}
        L.append(f"- A2 random directions: status {rd.get('status')}, kept {rd.get('kept')}, "
                 f"ratio quantiles (5/50/95%) {f(rd.get('ratio_quantiles'))}")
    for k in ("pairing_check", "mt_chrf", "openrouter_spend_usd", "degeneracy_max_per_model_curve"):
        L.append(f"- {k}: {json.dumps(S.get(k), default=float)}")
    if AU:
        L.append("\n## Audit\n")
        L.append(f"all_primary_checks_pass: {AU.get('all_primary_checks_pass')}")
        L.append("```\n" + json.dumps(AU.get("checks"), indent=1, default=float)[:6000] + "\n```")
        L.append("Placebos: " + json.dumps(AU.get("placebos"), default=float))
    (RESULTS / "summary_tables.md").write_text("\n".join(L) + "\n")
    print(f"wrote {RESULTS / 'summary_tables.md'} ({len(L)} lines)")


if __name__ == "__main__":
    main()
