#!/usr/bin/env python3
"""results/analysis.json (+ rq4.json, audit.json) -> results/summary_tables.md (every number traceable to analysis.json)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import MODELS, RESULTS  # noqa: E402

J1 = "surrogate/gemini"


def f(x, d=2):
    if x is None:
        return "–"
    if isinstance(x, bool):
        return str(x)
    if isinstance(x, (list, tuple)) and len(x) == 2:
        return f"[{f(x[0], d)}, {f(x[1], d)}]"
    try:
        return f"{float(x):.{d}f}"
    except (TypeError, ValueError):
        return str(x)


def main():
    A = json.loads((RESULTS / "analysis.json").read_text())
    L = ["# Summary tables (auto-generated by src/summarize.py from results/analysis.json)\n",
         f"Primary readout: **{J1}** (TF-IDF emulator of archived gemini-2.5-flash labels). Proxies: first-token log-odds s1>0, lexicon.\n"]
    L.append("## DEV decisions\n\n| model | L* | alpha-grid multiplier | lambda* | DEV R_EN / R_SL at lambda* | add-on band |\n|---|---|---|---|---|---|")
    for M, d in A["dev_decisions"].items():
        L.append(f"| {MODELS[M]['label']} | {d['layer']['L_star']} | {d['grid']['multiplier']} | {d['lambda']['lambda_star']} | "
                 f"{f(d['lambda']['R_EN_at_star'])} / {f(d['lambda']['R_SL_at_star'])} | {d.get('band', {}).get('chosen')} {d.get('band', {}).get('band', [None])[0]}-{d.get('band', {}).get('band', [None])[-1]} |")
    G = A["geometry"]
    L.append("\n## Geometry (t_post, winsorised diff-of-means; 95% item-bootstrap CIs)\n")
    L.append("| model | layer | f (SL energy in EN dir.) | cos(rEN,rSL) | ceiling | cos(EN-orig,EN-BT) | rho | d' SL along rEN | d' SL along rSL | perp share | cos(u_SLperp, d_lang) |\n|---|---|---|---|---|---|---|---|---|---|---|")
    for M in MODELS:
        if M not in G:
            continue
        a = G[M]["at_Lstar"]
        L.append(f"| {MODELS[M]['label']} | L*={G[M]['L_star']} | {f(a['f'], 3)} {f(a['f_ci95'], 3)} | {f(a['cos_EN_SL'], 3)} | {f(a['ceiling_cos_EN_SL'], 3)} | {f(a['cos_ENo_ENbt'], 3)} | "
                 f"{f(a['rho'], 3)} {f(a['rho_ci95'], 3)} | {f(a['dp_SL_along_rEN'])} | {f(a['dp_SL_along_rSL'])} | {f(a['perp_share'])} | {f(a['cos_uperp_dlang'])} |")
        b = G[M]["band_mean"]
        L.append(f"| {MODELS[M]['label']} | band {G[M]['band']} mean | {f(b['f'], 3)} | {f(b['cos_EN_SL'], 3)} | {f(b['ceiling_cos_EN_SL'], 3)} | {f(b['cos_ENo_ENbt'], 3)} | {f(b['rho'], 3)} | {f(b['dp_SL_along_rEN'])} | {f(b['dp_SL_along_rSL'])} | {f(b['perp_share'])} | {f(b['cos_uperp_dlang'])} |")
    if "contrast_gemma_minus_gams" in G:
        c = G["contrast_gemma_minus_gams"]
        L.append("\nGemma − GaMS (joint item bootstrap): " + "; ".join(
            f"{k}: own-L* {f(c[k]['own_Lstar'], 3)} {f(c[k]['own_Lstar_ci'], 3)}, band {f(c[k]['band'], 3)} {f(c[k]['band_ci'], 3)}, common layer {f(c[k]['common_layer_gemmaL'], 3)} {f(c[k]['common_layer_ci'], 3)}"
            for k in ("f", "rho", "dp_SL_along_rEN", "cos_EN_SL")))
        L.append(f"\nM-a geometry support (pre-registered): own L* {c['M-a_geometry_support_own_Lstar']}, band {c['M-a_geometry_support_band']}\n")
    L.append("\n## Induction (harmless Dolly prompts, +alpha*u at L*; alpha in K = alpha/|d| units; degenerate rows excluded)\n")
    for key, r in A["induction"].items():
        if not key.startswith(J1 + "|R|") or not key.endswith("|exclude"):
            continue
        M = key.split("|")[2]
        L.append(f"\n### {MODELS[M]['label']}\n\n| direction | lang | alpha50 (K) | 95% CI | censored | AUC | refusal at K=0 / 1 / max | deg at alpha50 | manip strict / KL-Spearman |\n|---|---|---|---|---|---|---|---|---|")
        lv = r["levels"]
        j1 = lv.index(1.0) if 1.0 in lv else None
        for ck, c in r["curves"].items():
            d_, lang = ck.split("|")
            rt = c["rate"]
            L.append(f"| {d_} | {lang} | {f(c['alpha50'])} | {f(c['alpha50_ci'])} | {c['censored']} | {f(c['auc'])} | {f(rt[0])} / {f(rt[j1]) if j1 else '–'} / {f(rt[-1])} | {f(c['degenerate_at_alpha50'])} | {c['manip_monotone']} / {f(c.get('manip_kl_spearman'))} |")
        cr = r["criteria"]
        for d_ in ("u_SLperp", "u_lang"):
            if d_ in cr:
                x = cr[d_]
                L.append(f"\n{d_}: R_lang {f(x['R_lang'])} {f(x['R_lang_ci'])}; R_rand {f(x['R_rand'])} {f(x['R_rand_ci'])}; dAUC SL−EN {f(x['dAUC_SL_minus_EN'])}; manip_ok {x['manip_ok']}; meets criterion: **{x['meets']}**")
        L.append(f"\nPositive control rEN reaches alpha50 on EN: {cr['positive_control_rEN_EN_reaches_alpha50']}; verdict M-b induction: **{r['verdict_Mb_induction']}**")
    if A.get("induction_contrast"):
        L.append("\nModel contrast (log R_lang Gemma − GaMS): " + json.dumps(A["induction_contrast"]))
    if A.get("induction_contrast_u_lang"):
        L.append("\nEXPLORATORY u_lang model contrast (log R_lang Gemma − GaMS): " + json.dumps(A["induction_contrast_u_lang"]))
    L.append("\n## Add-on neutralisation at lambda* (TEST160 harmful; hard_test benign; Dolly harmless)\n")
    for key, r in A["addon"].items():
        if not key.startswith(J1 + "|R|"):
            continue
        M = key.split("|")[2]
        L.append(f"\n### {MODELS[M]['label']}\n\n| condition | R_EN | R_SL | Lag | 95% CI | cut | cut CI | FA_EN | FA_SL | BenignExcess | 95% CI | dR_EN vs E0 (pp) | KL_EN / KL_E0 | SL/EN KL | degenerate |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        for c in r["conditions"]:
            x = r["conds"][c]
            L.append(f"| {c} | {f(x['R_EN_test160'])} | {f(x['R_SL_test160'])} | {f(x['Lag'])} | {f(x['Lag_ci'])} | {f(x['cut'])} | {f(x['cut_ci'])} | {f(x['FA_EN_hard'])} | {f(x['FA_SL_hard'])} | {f(x['BenignExcess'])} | {f(x['BenignExcess_ci'])} | {f(x['dR_EN_vs_E0_pp'], 1)} | {f(x.get('kl_ratio_en_vs_E0'))} | {f(x.get('c5a_SL_over_EN_kl'))} | {f(x.get('degenerate_test160'))} |")
        cr = r["criteria"]
        L.append(f"\nLag(E0) {f(cr['Lag_E0'])} {f(cr['Lag_E0_ci'])}; precondition (> m, CI excl 0): {cr['precondition_lag_gt_m_ci_excl0']}; underpowered (<1.2): {cr['underpowered_lag_lt_1.2']}; mean random cut {f(cr['mean_random_cut'])}")
        for c in [c for c in cr if c.startswith("A_")]:
            x = cr[c]
            L.append(f"- {c}: cut − random {f(x['cut_minus_random'])} {f(x['cut_minus_random_ci'])}; benign cut − random {f(x['benign_cut_minus_random'])} {f(x['benign_cut_minus_random_ci'])}; EN change < 5pp {x['EN_change_lt_5pp']}; KL gate {x['kl_gate_le_1.2']}; **primary met {x['primary_met']}**; one-mechanism {x['one_mechanism_met']}")
        L.append(f"\nMT noise (logit EN-orig − EN-BT): {json.dumps(r['mt_noise'])}")
    if A.get("G3_op"):
        L.append("\nG3_op (GaMS − Gemma Lag at E0; SCREEN items): " + json.dumps(A["G3_op"]))
    L.append("\n## Verdicts\n\n```\n" + json.dumps(A["verdict_table"], indent=1) + "\n```\n\nFinal (primary judge, both PARTIAL codings): " + json.dumps(A["final_verdict"]))
    jv = A.get("judge_validity", {})
    if "adjudication_error_matrix" in jv:
        L.append("\n## Judge validity: blind adjudication (author model, NOT human)\n\n| cell | n | gold REFUSE rate | surrogate sens / spec / kappa | Qwen (sample) sens / spec / n | s1 proxy kappa | lexicon kappa |\n|---|---|---|---|---|---|---|")
        for k, v in jv["adjudication_error_matrix"].items():
            L.append(f"| {k} | {v['n']} | {f(v['gold_refuse_rate'])} | {f(v['j1']['sens'])} / {f(v['j1']['spec'])} / {f(v['j1']['kappa'])} | {f(v['j2']['sens'])} / {f(v['j2']['spec'])} / {v['j2']['n']} | {f(v['s1']['kappa'])} | {f(v['lexicon']['kappa'])} |")
    if "corrected_headlines_j1_R" in A:
        L.append("\nRogan-Gladen corrected (adjudication error matrix): " + json.dumps(A["corrected_headlines_j1_R"]))
    if (RESULTS / "rq4.json").exists():
        rq = json.loads((RESULTS / "rq4.json").read_text())
        L.append("\n## RQ4 (frozen-core CHECK: is harmful/harmless still decodable after the edit?)\n")
        L.append("| model | state | arm | probe AUROC | shuffled | selectivity | ceiling | d' along ORIGINAL own-lang dir | cos(diff-of-means vs original) | transfer EN-BT->SL-MT |\n|---|---|---|---|---|---|---|---|---|---|")
        for M, r in rq.items():
            for st in r["states"]:
                k = f"{st}|post"
                if k not in r["at_Lstar"]:
                    continue
                v = r["at_Lstar"][k]
                for arm in ("en_bt", "sl_mt"):
                    a = v[arm]
                    L.append(f"| {MODELS[M]['label']} | {st} | {arm} | {f(a['auroc'], 3)} | {f(a['auroc_shuffled'], 3)} | {f(a['selectivity'], 3)} | {a['ceiling']} | {f(a['dprime_fixed_probe'])} | {f(a['cos_dm_vs_original'], 3)} | {f(v['transfer']['en_bt->sl_mt'], 3)} |")
        L.append("\nAt L* and every probed layer the probe is at ceiling (AUROC 1.00) in EVERY state, with the shuffled-label control at ~0.5: the edit does not remove harmfulness information, it changes what the model DOES with it. Reported as a CHECK (it holds largely by construction: Heretic removes a direction from the output weights, not the representation).\n")
    if (RESULTS / "audit.json").exists():
        au = json.loads((RESULTS / "audit.json").read_text())
        L.append(f"\n## Audit\n\n{au['n_pass']}/{au['n_checks']} checks pass. Failures: " + json.dumps([c for c in au["checks"] if not c["pass"]])[:3000])
    (RESULTS / "summary_tables.md").write_text("\n".join(L) + "\n")
    print("summary_tables.md written")


if __name__ == "__main__":
    main()
