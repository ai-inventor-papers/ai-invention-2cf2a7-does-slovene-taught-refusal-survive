#!/usr/bin/env python3
"""Render RESULTS.md from results/analysis.json + audit.json (every number in RESULTS.md comes from these files)."""
from __future__ import annotations

import json

from common import RESULTS, WS

A = json.loads((RESULTS / "analysis.json").read_text())
AU = json.loads((RESULTS / "audit.json").read_text()) if (RESULTS / "audit.json").exists() else {}
AM = json.loads((RESULTS / "protocol_amendments.json").read_text())
TRIALS = {m: len(json.loads((RESULTS / m / "trials.json").read_text())) for m in ("gemma_it", "gams3_it")
          if (RESULTS / m / "trials.json").exists()}
MOD = {"gemma_it": "Gemma-3-12B-IT", "gams3_it": "GaMS3-12B-Instruct"}


def f(x, d=3):
    try:
        return f"{float(x):.{d}f}"
    except (TypeError, ValueError):
        return str(x)


def est(e, d=3):
    if not isinstance(e, dict):
        return str(e)
    return f"{f(e['est'], d)} [{f(e['ci95'][0], d)}, {f(e['ci95'][1], d)}]"


L = []
w = L.append
w("# RESULTS — dir5 Heretic core screen (auto-generated by src/write_results_md.py)\n")
w(f"Primary readout: **{A['primary_readout']}** (pre-registered frozen lexicon). {A.get('readout_note','')}\n")
w(f"Judge rows per model: {json.dumps({k: (v.get('rows_per_model') if isinstance(v, dict) else None) for k, v in A.get('sensitivity_readouts', {}).items()})}\n")
w(f"Raw readout note (judge coverage {json.dumps({k: round(v, 3) for k, v in A['judge_coverage'].items()})}). "
  f"Trials completed per model: {json.dumps(TRIALS)} (target {AM.get('n_trials')}; all are TPE start-up (random) draws "
  f"with the same seed, verified identical across models). NF4 reduced precision. "
  f"95% CIs from 2,000 bootstrap resamples. m (5 pp SESOI in log-odds at base rate) = {f(A['m']['m'])}; "
  f"m2 (2×SESOI at prefill-5 flip rate) = {f(A['m']['m2'])}.\n")

w("## P0 — refusal on SCORE-400 (400 pairs × EN/SL)\n")
w("| model | condition | lang | R (lexicon) | mean s | SL-consistent | AUROC(s→R) |")
w("|---|---|---|---|---|---|---|")
for k, v in A["P0_descriptives"].items():
    m, c, l = k.split("|")
    if c not in ("orig", "selected"):
        continue
    w(f"| {MOD[m]} | {c} | {l} | {f(v.get('R'))} | {f(v.get('s'), 2)} | {f(v.get('sl_consistent', ''))} | {f(v.get('auroc_s_to_R'))} |")
for name, sec in (A.get("sensitivity_readouts") or {}).items():
    if sec.get("skipped"):
        w(f"\nSensitivity readout {name}: SKIPPED — {sec['skipped']} ({json.dumps(sec.get('rows_per_model'))})")
    else:
        w(f"\nSensitivity readout {name}: " + ", ".join(
            f"{MOD[k.split('|')[0]]} {k.split('|')[1]} {k.split('|')[2]} R={f(v.get('R'))}"
            for k, v in sec["P0_descriptives"].items() if k.split("|")[1] in ("orig", "selected")))
w("")
w(f"- DiD_ref = [GaMS(L_SL−L_EN) − Gemma(L_SL−L_EN)] on original models: {est(A.get('P0_DiD_ref_overall'))} "
  f"(ceiling rule triggered: {A.get('P0_ceiling_rule_triggered')}; s-based DiD co-primary: {est(A.get('P0_DiD_s_overall'), 2)} in s units).")
w(f"- D cross-check (low-EN minus high-EN categories): {est(A.get('P0_D_crosscheck'))} — dir2 owns C2.\n")

w("## C3 — Slovene refusal at matched English refusal (trial curve)\n")
c3 = A.get("C3", {})
for var in ("matched_first_k_trials", "all_trials", "startup_trials_only"):
    if var not in c3:
        continue
    w(f"**{var}**\n")
    w("| subset | G3 = a_GaMS − a_Gemma | slope b Gemma | slope b GaMS | trials in EN[.2,.8] (Gemma/GaMS) | extrapolated |")
    w("|---|---|---|---|---|---|")
    for sub in ("all_pairs", "TR_pairs", "low_EN", "high_EN"):
        e = c3[var].get(sub)
        if not e:
            continue
        sp = e["support_trials_EN_in_[.2,.8]"]
        w(f"| {sub} (n={e['n_pairs']}) | {est(e['G3'])} | {est(e['b_slope']['gemma_it'])} | {est(e['b_slope']['gams3_it'])} | "
          f"{sp['gemma_it']}/{sp['gams3_it']} | {e['extrapolated']} |")
    w(f"\nG3_low − G3_high (ALT-1 category version): {est(c3[var].get('G3_low_minus_high'))}\n")
if c3.get("lambda_curve"):
    w(f"λ-curve variant: G3 = {est(c3['lambda_curve']['G3'])}; points: " + json.dumps(
        {MOD[m]: {"lambda": v["lambda"], "x": [round(a, 2) for a in v["x_EN_logodds"]], "y": [round(a, 2) for a in v["y_SL_logodds"]]}
         for m, v in c3["lambda_curve"]["points"].items()}) + "\n")
if c3.get("s_variant"):
    w(f"s1 variant: G3 in s1 units = {f(c3['s_variant']['G3_s_units'], 2)} ({json.dumps({MOD[m]: {k: round(v, 2) for k, v in d.items()} for m, d in c3['s_variant']['per_model'].items()})})\n")

w("## C5a — Slovene/English first-token KL leakage vs random-direction edits (EVAL-KL, 100 paired stems)\n")
w("| model | control | ratio_edit SL/EN | ratio_random SL/EN | excess | leakage supported |")
w("|---|---|---|---|---|---|")
for m, d in A.get("C5a", {}).items():
    for v, e in d.items():
        w(f"| {MOD[m]} | {v} | {est(e['ratio_edit_SL_over_EN'])} | {est(e['ratio_rand_SL_over_EN'])} | {est(e['excess'])} | {e['leakage_supported']} |")
w("")
w("## C5b — bilingual re-selection gain\n")
for m, e in A.get("C5b", {}).items():
    w(f"- {MOD[m]}: pick trial {e['pick']}, {e['n_candidates']} candidates, resel {e['resel']} (== pick: {e['resel_equals_pick']}), "
      f"gain {est(e['gain'])}, supported: {e['supported']}")
w("")
w("## ALT-4 — compliant-prefill flip test (original models; items refused at k=0)\n")
a4 = A.get("ALT4", {})
if "prefill_signature" in a4:
    ps = a4["prefill_signature"]
    for l in ("en", "sl"):
        e = ps["Sig"][l]
        w(f"- {l.upper()}: flip rate Gemma {f(e['flip_rate']['gemma_it'])} (n={e['n_refused_k0']['gemma_it']}), GaMS "
          f"{f(e['flip_rate']['gams3_it'])} (n={e['n_refused_k0']['gams3_it']}); Sig = F_GaMS − F_Gemma = {est(e)}")
    w(f"- survive: {ps['survive']}, z_c = {f(ps['z_c'], 2)}, language interaction {f(ps['lang_interaction'])}")
    w(f"- depth curve (flip rate by k): {json.dumps(a4.get('prefill_depth_curve'))}")
if "pareto_hv_ratio_gams_over_gemma" in a4:
    w(f"- Pareto hypervolume ratio GaMS/Gemma (reduced-trial, random-search fronts): {est(a4['pareto_hv_ratio_gams_over_gemma'])}")
w("")
w("## Selection rule (pre-registered; C3 conjunct only — C1/D/DiD parts belong to dir2)\n")
w("```json\n" + json.dumps(A.get("selection"), indent=1, default=float) + "\n```\n")
w("## Judge validation (lexicon vs gemini-2.5-flash)\n")
jv = A.get("judge_validation")
if isinstance(jv, dict):
    w("κ is deflated by skewed marginals here (kappa paradox), so raw agreement and PABAK = 2·agreement−1 are shown too.\n")
    w("| cell | n | agreement | PABAK | κ (partial=comply) | κ (partial=refuse) | lexicon rate | judge refuse (reweighted) | AUROC(s→judge) |")
    w("|---|---|---|---|---|---|---|---|---|")
    for k, v in jv.items():
        if isinstance(v, dict) and "kappa_partial_as_comply" in v:
            w(f"| {k} | {v['n']} | {f(v.get('percent_agreement'))} | {f(v.get('pabak'))} | {f(v['kappa_partial_as_comply'])} | "
              f"{f(v['kappa_partial_as_refuse'])} | {f(v['lexicon_rate_population'])} | "
              f"{f(v['judge_refuse_rate_reweighted'])} | {f(v.get('auroc_s_to_judge_refuse'))} |")
    for k in ("heretic_keyword_recall_gap_gams_minus_gemma", "n_unparsed"):
        if k in jv:
            w(f"- {k}: {f(jv[k])}")
w("")
w("## Sanity gates\n")
w("```json\n" + json.dumps(A.get("sanity_gates"), indent=1, default=float)[:6000] + "\n```\n")
w(f"Pair correspondence (gemini-2.5-flash T/R/U): {json.dumps(A.get('pair_grades_summary'))}\n")
if AU:
    w(f"## Audit\n\n{AU.get('n_match')}/{AU.get('n_checks')} headline numbers re-derived through an independent pandas/polyfit path. "
      f"Placebos: ```{json.dumps(AU.get('placebo'), default=float)}```\n")
(WS / "RESULTS.md").write_text("\n".join(L))
print("RESULTS.md written", len(L), "lines")
